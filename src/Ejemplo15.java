import java.util.Scanner;

public class Ejemplo15 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);


        int nota;
        System.out.println("Ingresa la nota");
        nota = sc.nextInt();

        switch (nota)
        {
            case 1:
                System.out.println("El nota es uno");
                break;
            case 2:
                System.out.println("El nota es dos");
                break;
            case 3:
                System.out.println("El nota es tres");
                break;
            case 4:
                System.out.println("El nota es cuatro");
                break;
            case 5:
                System.out.println("El nota es cinco");
                break;
            case 6:
                System.out.println("El nota es seis");
                break;
            case 7:
                System.out.println("El nota es siete");
                break;
            case 8:
                System.out.println("El nota es ocho");
                break;
            case 9:
                System.out.println("El nota es nueve");
                break;
            case 10:
                System.out.println("El nota es diez");
                break;


        }









    }
}
